CREATE TABLE IF NOT EXISTS build_state(
  id INTEGER PRIMARY KEY CHECK(id=1), generation TEXT NOT NULL, epoch TEXT NOT NULL,
  watermark INTEGER NOT NULL, scan_after INTEGER, ready INTEGER NOT NULL, next_block INTEGER NOT NULL
) STRICT;
CREATE TABLE IF NOT EXISTS threads(
  slot INTEGER PRIMARY KEY, id TEXT NOT NULL UNIQUE, revision TEXT NOT NULL
) STRICT;
CREATE TABLE IF NOT EXISTS locations(
  position INTEGER PRIMARY KEY, id BLOB NOT NULL, stamp INTEGER NOT NULL,
  offset_seconds INTEGER NOT NULL, thread INTEGER NOT NULL, start INTEGER NOT NULL,
  length INTEGER NOT NULL
) STRICT;
CREATE TABLE IF NOT EXISTS terms(
  id INTEGER PRIMARY KEY, word TEXT UNIQUE NOT NULL
) STRICT;
CREATE TABLE IF NOT EXISTS blocks(
  id INTEGER PRIMARY KEY, oldest_stamp INTEGER NOT NULL, oldest BLOB NOT NULL
) STRICT;
CREATE TABLE IF NOT EXISTS postings(
  block INTEGER NOT NULL, term INTEGER NOT NULL, stamp INTEGER NOT NULL,
  newest BLOB NOT NULL, positions BLOB NOT NULL,
  PRIMARY KEY(block,term)
) STRICT, WITHOUT ROWID;
