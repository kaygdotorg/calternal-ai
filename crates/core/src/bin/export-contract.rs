//! Generate schemas and TypeScript declarations from the pure Rust contract; `--check` fails on drift.
//! Preserve Rust type and field documentation in TypeScript and trim trailing line whitespace.
#![deny(missing_docs)]
#![deny(rustdoc::broken_intra_doc_links)]
use calternal_core::*;
use std::{fs, path::PathBuf};
use ts_rs::TS;
fn main() -> Result<(), Box<dyn std::error::Error>> {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../..");
    let args: Vec<_> = std::env::args().skip(1).collect();
    let check = args == ["--check"];
    if !args.is_empty() && !check {
        return Err("usage: export-contract [--check]".into());
    }
    let schema = format!(
        "{}\n",
        serde_json::to_string_pretty(&schemars::schema_for!(Contract))?
    );
    let mut ts = String::from(
        "// Generated by cargo run -p calternal-core --bin export-contract. Do not edit.\n/** Arbitrary JSON object at the transport boundary; validate operation-specific values before use. */\nexport type JsonObject = Record<string, unknown>;\n",
    );
    macro_rules! emit {
        ($($t:ty),* $(,)?) => {$(
            if let Some(docs) = <$t>::DOCS {
                ts.push_str(docs);
                ts.push('\n');
            }
            ts.push_str("export ");
            ts.push_str(&<$t>::decl());
            ts.push('\n');
        )*};
    }
    emit!(
        OperationRequest,
        ErrorCode,
        ApiError,
        Success<serde_json::Value>,
        Failure,
        OperationResponse<serde_json::Value>,
        NoteSummary,
        Note,
        NoteVersion,
        NotesListInput,
        NotesGetInput,
        NotesCreateInput,
        NotesUpdateInput,
        NotesHistoryInput,
        NotesListResult,
        NoteResult,
        NotesHistoryResult,
        PluginsListInput,
        PluginInput,
        PluginDependency,
        PluginOperation,
        ExtensionPoint,
        PluginView,
        PluginManifest,
        PluginState,
        PluginsListResult,
        PluginResult,
        PluginPreviewResult,
        Stats,
        SummarizeResult,
        GenUiAction,
        GenUiNode,
        GenUiView,
        SpaceRole,
        SpaceGrant,
        Principal,
        OperationDescription,
        DescribeResult,
        WorkerResource,
        WorkerOperation,
        WorkerRequest,
        WorkerErrorCode,
        WorkerError,
        WorkerSuccess,
        WorkerFailure,
        WorkerResponse
    );
    // serde_json::Value is deliberately unknown at the transport boundary.
    ts = ts.replace("JsonValue", "unknown");
    // ts-rs inserts spaces before field-comment newlines; normalize only line ends.
    let mut formatted_ts = String::with_capacity(ts.len());
    for line in ts.lines() {
        formatted_ts.push_str(line.trim_end());
        formatted_ts.push('\n');
    }
    let operations = format!("{}\n", serde_json::to_string_pretty(&operation_catalog())?);
    let artifacts = [
        ("contract/v0.schema.json", schema),
        ("packages/contracts/src/index.ts", formatted_ts),
        ("contract/operations.json", operations),
    ];
    let mut drift = Vec::new();
    for (path, expected) in artifacts {
        let destination = root.join(path);
        if check {
            if fs::read_to_string(&destination).ok().as_deref() != Some(expected.as_str()) {
                drift.push(path);
            }
        } else {
            fs::create_dir_all(destination.parent().unwrap())?;
            fs::write(destination, expected)?;
        }
    }
    if !drift.is_empty() {
        return Err(format!("contract artifacts need regeneration: {}", drift.join(", ")).into());
    }
    if check {
        println!("contract artifacts match Rust models");
    }
    Ok(())
}
