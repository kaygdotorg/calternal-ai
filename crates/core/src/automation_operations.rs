//! Space operations for authored skills and scheduled provider turns.
use crate::{AgentMode, JsonObject, OperationDescription, OperationRisk, PeopleTarget};
use calternal_types::{Capability, Error};
use schemars::JsonSchema;
use serde::{Deserialize, Serialize};
use ts_rs::TS;

/// An operation selecting the named skill in a space.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct SkillTarget {
    /// Owning space UUID.
    pub space_id: String,
    /// Name of the bundle directory.
    pub name: String,
}

/// The entire portable SKILL.md document to write.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct SkillWrite {
    /// Owning space UUID.
    pub space_id: String,
    /// Name of the bundle directory.
    pub name: String,
    /// Standard YAML frontmatter followed by Markdown instructions.
    pub markdown: String,
    /// Required for update and omitted for create.
    #[ts(optional)]
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub base_revision: Option<String>,
}

/// A conditional removal of a skill bundle.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct SkillRemove {
    /// Owning space UUID.
    pub space_id: String,
    /// Name of the bundle directory.
    pub name: String,
    /// Revision returned by the read operation.
    pub base_revision: String,
}

/// Descriptor and exact Markdown for one skill.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct SkillDocument {
    /// Descriptor also used by the palette.
    #[serde(flatten)]
    pub descriptor: crate::SkillMatch,
    /// Standard portable Markdown contents.
    pub markdown: String,
    /// Opaque version to send on update or remove.
    pub revision: String,
}

/// A single skill read or mutation result.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct SkillResult {
    /// Current skill contents.
    pub skill: SkillDocument,
}

/// Read-only schedule preview input.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct AutomationPreview {
    /// Owning space UUID.
    pub space_id: String,
    /// Original words as entered by the creator.
    pub schedule_text: String,
}

/// Normalized schedule and the exact details to confirm when saving.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationSchedule {
    /// Original schedule phrase, including its original spelling and whitespace.
    pub schedule_text: String,
    /// Canonical calendar expression generated by the server.
    pub schedule: String,
    /// Normalized schedule in plain words.
    pub human: String,
    /// IANA zone used to compute the next instant.
    pub timezone: String,
    /// Next instant in UTC epoch milliseconds, when scheduled.
    #[ts(type = "number | null")]
    pub next_run_ms: Option<i64>,
}

/// Space and existing automation identity.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct AutomationTarget {
    /// Owning space UUID.
    pub space_id: String,
    /// Stable automation UUID.
    pub id: String,
}

/// A conditional pause, enable or removal.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct AutomationRevision {
    /// Owning space UUID.
    pub space_id: String,
    /// Stable automation UUID.
    pub id: String,
    /// Opaque definition revision.
    pub base_revision: String,
}

/// Create an automation using the schedule approved in the preview.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct AutomationCreate {
    /// Owning space UUID.
    pub space_id: String,
    /// Readable title and filename stem.
    pub name: String,
    /// Markdown prompt submitted as the initial turn.
    pub prompt: String,
    /// Original schedule phrase.
    pub schedule_text: String,
    /// Canonical expression shown by the preview.
    pub schedule: String,
    /// Account zone confirmed in the preview.
    pub timezone: String,
    /// Permission mode for new turns.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub mode: Option<AgentMode>,
    /// Creator-owned machine or the creator's authorized sandbox when omitted.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub machine_id: Option<String>,
}

/// Change selected fields, sending all three preview fields to change the schedule.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
#[serde(deny_unknown_fields)]
pub struct AutomationUpdate {
    /// Owning space UUID.
    pub space_id: String,
    /// Stable automation UUID.
    pub id: String,
    /// Opaque current definition revision.
    pub base_revision: String,
    /// New display title.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub name: Option<String>,
    /// New Markdown prompt.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub prompt: Option<String>,
    /// Original words for a changed or reconfirmed schedule.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub schedule_text: Option<String>,
    /// Canonical expression for the same schedule preview.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub schedule: Option<String>,
    /// Account zone confirmed by that preview.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub timezone: Option<String>,
    /// Mode to apply to subsequent runs.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub mode: Option<AgentMode>,
    /// Machine UUID, or an empty string to select the authorized sandbox.
    #[serde(default)]
    #[ts(optional = nullable)]
    pub machine_id: Option<String>,
}

/// One scheduling outcome, with a thread when a turn was admitted.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationOutcome {
    /// Stable run lifecycle status.
    pub status: String,
    /// Scheduled instant in UTC epoch milliseconds, absent for manual runs.
    #[ts(type = "number | null")]
    pub scheduled_at_ms: Option<i64>,
    /// Time this outcome was recorded, in UTC epoch milliseconds.
    #[ts(type = "number")]
    pub at_ms: i64,
    /// Admitted thread UUID, if any.
    pub thread_id: Option<String>,
    /// Caller-safe explanation for an exceptional outcome.
    pub reason: Option<String>,
}

/// An automation's status and saved definition metadata.
#[derive(Debug, Clone, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationRecord {
    /// Stable automation UUID.
    pub id: String,
    /// Display title.
    pub name: String,
    /// Opaque current definition revision.
    pub revision: String,
    /// Relative Markdown path in the owning space.
    pub path: String,
    /// Original and normalized schedule details.
    #[serde(flatten)]
    pub timing: AutomationSchedule,
    /// Whether scheduled execution is enabled.
    pub enabled: bool,
    /// Permission mode for subsequent runs.
    pub mode: AgentMode,
    /// Most recent recorded outcome, absent before the first occurrence.
    pub last: Option<AutomationOutcome>,
    /// Last stop reason, if automatic execution was revoked.
    #[serde(skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub stop_reason: Option<String>,
    /// Creator's new account zone, when a schedule move requires confirmation.
    #[serde(skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub account_timezone: Option<String>,
    /// Explicit machine when visible to the creator.
    #[serde(skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub machine_id: Option<String>,
    /// Exact prompt supplied with individual reads and definition edits.
    #[serde(skip_serializing_if = "Option::is_none")]
    #[ts(optional)]
    pub prompt: Option<String>,
}

/// A space's bounded list of automation definitions.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationList {
    /// Definitions and their scheduling status.
    pub automations: Vec<AutomationRecord>,
}

/// A single automation definition.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationResult {
    /// Definition and latest scheduling status.
    pub automation: AutomationRecord,
}

/// Next scheduled instant for an automation.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationNext {
    /// UTC epoch milliseconds, or null when paused or stopped.
    #[ts(type = "number | null")]
    pub next_run_ms: Option<i64>,
}

/// Latest recorded run or skip.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationLast {
    /// Null before the first outcome.
    pub last: Option<AutomationOutcome>,
}

/// Admitted thread for a manual run.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct AutomationThread {
    /// Stable UUID of the new thread.
    pub thread_id: String,
}

/// Acknowledgement of a successful removal into Trash.
#[derive(Debug, Serialize, Deserialize, JsonSchema, TS)]
pub struct RemovalResult {
    /// True after the committed removal.
    pub ok: crate::True,
}

/// One native space operation used by discovery, validation and authorization.
pub struct AutomationOperation {
    /// Stable operation identifier.
    pub id: &'static str,
    /// Current space capability required for the operation.
    pub capability: Capability,
    /// Available effect before the operation-specific authority checks.
    pub risk: OperationRisk,
    description: &'static str,
    schemas: fn(&AutomationOperation) -> OperationDescription,
    validate: fn(&JsonObject) -> Result<(), Error>,
}

impl AutomationOperation {
    pub(crate) fn describe(&self) -> OperationDescription {
        (self.schemas)(self)
    }

    pub(crate) fn validate(&self, input: &JsonObject) -> Result<(), Error> {
        (self.validate)(input)?;
        input
            .get("space_id")
            .and_then(serde_json::Value::as_str)
            .and_then(|space| calternal_types::SpaceId::parse(space).ok())
            .ok_or_else(|| Error::invalid_input("space_id must be a UUID"))?;
        Ok(())
    }
}

fn schemas<I: JsonSchema, O: JsonSchema>(op: &AutomationOperation) -> OperationDescription {
    OperationDescription {
        required_capability: Some(op.capability.name().into()),
        target: Some(PeopleTarget::Space),
        id: op.id.into(),
        description: op.description.into(),
        risk: op.risk,
        mutates: op.risk != OperationRisk::Read,
        input_schema: serde_json::from_value(serde_json::json!(schemars::schema_for!(I)))
            .expect("object schema"),
        output_schema: serde_json::from_value(serde_json::json!(schemars::schema_for!(O)))
            .expect("object schema"),
    }
}

macro_rules! operation {
    ($id:literal, $description:literal, $capability:ident, $risk:ident, $in:ty => $out:ty) => {
        AutomationOperation {
            id: $id,
            description: $description,
            capability: Capability::$capability,
            risk: OperationRisk::$risk,
            schemas: schemas::<$in, $out>,
            validate: |input| crate::validation::decode::<$in>(input).map(|_| ()),
        }
    };
}

/// Native skill and automation operations, beyond the existing palette skill list.
pub const AUTOMATION_OPERATIONS: &[AutomationOperation] = &[
    operation!("skills.read", "Read the portable document of a named skill", SpaceRead, Read, SkillTarget => SkillResult),
    operation!("skills.create", "Create a portable skill in its own space folder", ContentWrite, Reversible, SkillWrite => SkillResult),
    operation!("skills.update", "Write a new revision of a skill document", ContentWrite, Reversible, SkillWrite => SkillResult),
    operation!("skills.remove", "Move a skill bundle to Trash", ContentWrite, Reversible, SkillRemove => RemovalResult),
    operation!("automations.preview_schedule", "Parse a schedule and preview it in your account zone", SpaceRead, Read, AutomationPreview => AutomationSchedule),
    operation!("automations.list", "List a space's automation definitions and status", SpaceRead, Read, crate::PluginsListInput => AutomationList),
    operation!("automations.read", "Read an automation and its prompt", SpaceRead, Read, AutomationTarget => AutomationResult),
    operation!("automations.create", "Create an automation for your account", ContentWrite, WidensAccess, AutomationCreate => AutomationResult),
    operation!("automations.update", "Update your automation at a known revision", ContentWrite, WidensAccess, AutomationUpdate => AutomationResult),
    operation!("automations.enable", "Enable scheduled runs for your automation", ContentWrite, WidensAccess, AutomationRevision => AutomationResult),
    operation!("automations.pause", "Pause future runs for an automation", ContentWrite, Reversible, AutomationRevision => AutomationResult),
    operation!("automations.remove", "Move an automation definition to Trash", ContentWrite, Reversible, AutomationRevision => RemovalResult),
    operation!("automations.run_now", "Start a thread for your automation", ContentWrite, WidensAccess, AutomationTarget => AutomationThread),
    operation!("automations.next_run", "Read the next scheduled run", SpaceRead, Read, AutomationTarget => AutomationNext),
    operation!("automations.last_run", "Read the latest automation outcome", SpaceRead, Read, AutomationTarget => AutomationLast),
];

/// Look up a declared automation or skill operation without allocations.
pub fn automation_operation(id: &str) -> Option<&'static AutomationOperation> {
    AUTOMATION_OPERATIONS
        .iter()
        .find(|operation| operation.id == id)
}
