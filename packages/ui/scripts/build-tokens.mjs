// Emits src/styles/tokens.generated.css from tokens/tokens.json (the one source). Run by `npm run tokens`,
// and first by every build, dev and test script. Pure: no network, no dependencies.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const t = JSON.parse(readFileSync(join(root, "tokens/tokens.json"), "utf8"));

// The phone's type scale comes from the measured iOS Dynamic Type table (default "Large" column), not from hand-typed sizes.
const study = JSON.parse(readFileSync(join(root, "../../docs/native-ui-study.json"), "utf8"));
const LARGE = study.ios.dynamicType.sizes.indexOf("large");
for (const [token, style] of Object.entries(t.touchText)) {
  if (token.startsWith("$")) continue;
  const row = study.ios.dynamicType[style];
  if (!row) throw new Error(`native-ui-study.json has no Dynamic Type style ${style}`);
  t.touch[token] = `calc(${row[LARGE][0]} * var(--type-px))`;
}

// One "UI size" scale (--ui-scale, set from Settings, 1 by default) multiplies the whole interface together: type (through --type-px, a rem fraction), and every
// spacing, radius, control and region size below. Blur radii and safe-area insets are not sized by it.
const SCALED = /^(s-\d+|r-card|r-pane|r-select|inset|tier-cap|cap-offset|side-w|right-w|row-h(-settings)?|bar-h|pill-h|pad-region)$/;
const scaled = (k, v) => (SCALED.test(k) && /^\d+(\.\d+)?px$/.test(v) ? `calc(${v} * var(--ui-scale, 1))` : k === "type-px" ? `calc(${v} * var(--ui-scale, 1))` : v);
const decl = (obj, pad = "  ") =>
  Object.entries(obj)
    .filter(([k]) => !k.startsWith("$"))
    .map(([k, v]) => `${pad}--${k}: ${scaled(k, v)};`)
    .join("\n");

/** A spring as a CSS linear() easing (Apple's damping-ratio/response model); never longer than 300 ms. */
function spring(damping, response) {
  const w = (2 * Math.PI) / response;
  const at = (x) => {
    if (damping >= 1) return 1 - (1 + w * x) * Math.exp(-w * x);
    const wd = w * Math.sqrt(1 - damping * damping);
    return 1 - Math.exp(-damping * w * x) * (Math.cos(wd * x) + ((damping * w) / wd) * Math.sin(wd * x));
  };
  let end = response;
  for (let x = 0; x < 4; x += 0.004) if (Math.abs(1 - at(x)) > 0.001) end = x;
  end = Math.max(end, 0.05);
  const steps = 40;
  const pts = Array.from({ length: steps + 1 }, (_, i) => (i === steps ? 1 : at((end * i) / steps)).toFixed(4));
  return { easing: `linear(${pts.join(", ")})`, ms: Math.min(300, Math.round(end * 1000)) };
}
const springs = Object.entries(t.springs)
  .filter(([k]) => !k.startsWith("$"))
  .flatMap(([name, [d, r]]) => {
    const s = spring(d, r);
    return [`  --${name}: ${s.easing};`];
  })
  .join("\n");

/** The no-wallpaper ground: the mesh's mean colour, flat. A gradient is not an acceptable default (owner, 2026-11-17); a wallpaper replaces this as soon as it is ready. */
function backdrop(colors) {
  const mean = colors
    .map((c) => [1, 3, 5].map((j) => parseInt(c.slice(j, j + 2), 16)))
    .reduce((a, b) => a.map((v, i) => v + b[i]), [0, 0, 0])
    .map((v) => Math.round(v / colors.length));
  return `rgb(${mean.join(" ")})`;
}

const css = `/* GENERATED by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit. */
:root {
  color-scheme: light;
${decl(t.base)}
${decl(t.touch)}
${decl(t.light)}
${springs}
  --backdrop: ${backdrop(t.backdrop.light)};
  --grain-a: ${t.appearance["grain-a"]};
}
@media (min-width: 760px) and (hover: hover) and (pointer: fine) {
  :root {
${decl(t.desktop, "    ")}
  }
}
:root[data-scheme="dark"] {
  color-scheme: dark;
${decl(t.dark)}
  --backdrop: ${backdrop(t.backdrop.dark)};
}
@media (prefers-reduced-transparency: reduce) {
  :root { --glass-a: 0.94; --card-tint-a: 0.96; --side-tint-a: 0.9; }
  :root[data-scheme="dark"] { --glass-a: 0.95; --card-tint-a: 0.96; --side-tint-a: 0.9; }
}
@media (prefers-reduced-motion: reduce) {
  :root {
    --dur-fast: 1ms; --dur-sheet: 1ms; --dur-leave: 1ms; --dur-base: 1ms; --dur-slow: 1ms;
    --spring: linear;
  }
}
`;
writeFileSync(join(root, "src/styles/tokens.generated.css"), css);
console.log(`tokens: wrote ${css.length} bytes`);
