// Generates src/generated/model.ts from the two sealed schemas (contract/description-v2.schema.json and contract/host-catalogue-v2.json) so no shape the contract owns is written twice.
// The two are merged into one flat set of definitions first: the description schema cites the catalogue's shapes by address (`host-catalogue-v2.json#/$defs/X`), and each such citation becomes a plain
// local reference to the same name (the description's own `MemberRowCacheRecord` and `WindowReply` only repeat the catalogue's, so the catalogue's are kept). `--check` regenerates in memory and fails
// when the committed file differs (the test and `npm run check` run it).
import { compile } from "json-schema-to-typescript";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const readJson = (p) => JSON.parse(readFileSync(join(root, p), "utf8"));
const out = join(root, "packages/description/src/generated/model.ts");

/** Rewrites every citation of the catalogue (relative or absolute address) into a local `#/$defs/Name` reference. */
function localise(node) {
  if (Array.isArray(node)) return node.map(localise);
  if (node && typeof node === "object") {
    const o = {};
    for (const [k, v] of Object.entries(node)) o[k] = k === "$ref" && typeof v === "string" ? v.replace(/^(?:https:\/\/calternal\.cloud\/contract\/)?host-catalogue-v2\.json#/, "#") : localise(v);
    return o;
  }
  return node;
}

/** Drops what a type cannot say (conditional rules: `allOf` of if/then/else, `not`, `dependentRequired`); the schemas stay the authority for those, and the tests check every fixture against them. */
function structural(node) {
  if (Array.isArray(node)) return node.map(structural);
  if (node && typeof node === "object") {
    const o = {};
    for (const [k, v] of Object.entries(node)) {
      if (["allOf", "if", "then", "else", "not", "dependentRequired"].includes(k)) continue;
      // inside `properties` the keys are property NAMES (an invoke has a `then`), so only their values are filtered
      o[k] = k === "properties" && v && typeof v === "object" && !Array.isArray(v) ? Object.fromEntries(Object.entries(v).map(([n, d]) => [n, structural(d)])) : structural(v);
    }
    return o;
  }
  return node;
}

/** The merged model as TypeScript text. */
export async function generate() {
  const description = readJson("contract/description-v2.schema.json"), catalogue = readJson("contract/host-catalogue-v2.json");
  const defs = { ...structural(localise(description.$defs)) };
  for (const [name, def] of Object.entries(structural(localise(catalogue.$defs)))) defs[name] = def; // the catalogue's shapes win where both name one
  for (const [name, def] of Object.entries(defs)) if (def && typeof def === "object" && !def.title && !def.$ref) defs[name] = { title: name, ...def }; // a title names the type, so recursive shapes (a stack of nodes) refer to themselves by name
  const merged = { $schema: description.$schema, title: "ContractModel", $defs: defs };
  const ts = await compile(merged, "ContractModel", { unreachableDefinitions: true, maxItems: -1, additionalProperties: false, strictIndexSignatures: false, format: false, bannerComment: "" });
  const clean = ts.replace(/\/\*\*\n( \*[^\n]*\n)*? \* This interface was referenced by[\s\S]*?\*\/\n/g, (m) => { const body = m.split("\n").filter((l) => !/This interface was referenced|via the `definition`|^ \* ?$/.test(l)); return body.length > 2 ? body.join("\n") : ""; });
  return `/* GENERATED by packages/description/scripts/generate-types.mjs from contract/description-v2.schema.json and contract/host-catalogue-v2.json. Do not edit; run \`npm run types -w @calternal/description\`. */\n/* eslint-disable */\n\n${clean}`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = await generate();
  if (process.argv.includes("--check")) {
    let have = ""; try { have = readFileSync(out, "utf8"); } catch { /* none */ }
    if (have !== text) { console.error("src/generated/model.ts is out of date with the contract schemas: run `npm run types -w @calternal/description`."); process.exit(1); }
  } else writeFileSync(out, text);
}
