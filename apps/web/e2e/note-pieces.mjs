// The editor's lazy pieces: frontmatter hidden, block ID markers hidden, a table drawn as a grid, a code fence coloured, and none of their chunks fetched for a plain note. Usage: node e2e/note-pieces.mjs
import { chromium } from "playwright";
import { serve, BASE, DEVICES } from "./lib.mjs";
const stop = await serve(); const b = await chromium.launch(); let bad = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) bad++; };
const ctx = await b.newContext({ ...DEVICES.desktop }); const page = await ctx.newPage();
const js = []; page.on("request", (r) => { if (r.url().endsWith(".js")) js.push(r.url().split("/").pop()); });
await page.goto(BASE + "/notes/n-2?firstrun=0"); await page.waitForSelector(".cm-content"); await page.waitForTimeout(800);
const plainJs = [...js];
ok(!plainJs.some((n) => /^(tables|code|ids-view|frontmatter|language-data|javascript)/.test(n)), `a plain note fetches no lazy piece (${plainJs.length} scripts)`);
await page.goto(BASE + "/notes/n-rich?firstrun=0"); await page.waitForSelector(".cm-content"); await page.waitForSelector(".cm-grid table", { timeout: 8000 }).catch(() => {});
await page.waitForTimeout(1200);
const text = await page.evaluate(() => document.querySelector(".cm-content").innerText);
ok(!text.includes("title: Rich note") && text.includes("Rich note"), "frontmatter is not drawn");
ok(!text.includes("^k2m8"), "block ID markers are not drawn");
ok(await page.locator(".cm-grid th").count() === 3 && await page.locator(".cm-grid tbody tr").count() === 2, "the table is a grid (3 columns, 2 rows)");
ok(await page.locator(".cm-grid td").nth(2).evaluate((e) => getComputedStyle(e).textAlign) === "right", "column alignment follows the delimiter row");
const colours = await page.evaluate(() => { const c = new Set(); document.querySelectorAll(".cm-codeblock span").forEach((s) => c.add(getComputedStyle(s).color)); return c.size; });
ok(colours >= 3, `the code fence is coloured (${colours} colours)`);
await page.locator(".cm-grid").first().click(); await page.waitForTimeout(300);
ok(await page.locator(".cm-grid").count() === 0 && (await page.evaluate(() => document.querySelector(".cm-content").innerText)).includes("| Root |"), "clicking the grid brings the raw rows back");
// Block IDs through the editor: a new task gets a marker, typing at the end of a marked line stays before it, Enter keeps it on the first part.
await page.goto(BASE + "/notes/n-rich?firstrun=0&test=1"); await page.waitForSelector(".cm-grid table"); await page.waitForTimeout(800);
const doc = () => page.evaluate(() => window.__block.value);
ok((await doc()).includes("- [x] hide the markers"), "the second task starts with no marker yet");
await page.evaluate(() => { const v = window.__block; const i = v.value.indexOf("- [ ] write the grid"); v.view.dispatch({ selection: { anchor: v.value.indexOf("\n", i) } }); v.view.focus(); });
await page.keyboard.type(" now");
ok((await doc()).includes("write the grid now ^k2m8q1w4zre7k3f9"), "typing at the end of a marked line lands before its marker");
await page.keyboard.press("Enter"); await page.keyboard.type("a new task is not made by typing alone");
ok(/- \[ \] a new task is not made by typing alone/.test(await doc()), "Enter continues the task list");
await page.keyboard.press("Control+a");
await page.evaluate(() => { const v = window.__block; const i = v.value.indexOf("- [ ] a new task"); v.view.dispatch({ selection: { anchor: i + 6 } }); });
await page.keyboard.press("Enter");
await page.waitForTimeout(300);
const after = await doc();
ok(/- \[ \] write the grid now \^k2m8q1w4zre7k3f9\n/.test(after), "the first task keeps its marker through Enter on another item");
ok((after.match(/\^[0-9a-z]{16}/g) ?? []).length >= 2 && new Set(after.match(/\^[0-9a-z]{16}/g)).size === (after.match(/\^[0-9a-z]{16}/g) ?? []).length, "new tasks got their own IDs, all different");
await b.close(); stop();
console.log(bad ? `${bad} FAIL` : "all pass"); process.exit(bad ? 1 : 0);
