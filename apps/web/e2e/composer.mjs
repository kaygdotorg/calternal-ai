// The thread composer on the palette's engine: highlighted words, the @ picker (grouped), / for skills, context chips, Enter sends.
import { chromium } from "playwright";
import { serve, open } from "./lib.mjs";
const stop = await serve(); const b = await chromium.launch();
let bad = 0;
const ok = (n, p, note = "") => { console.log(`${p ? "PASS" : "FAIL"}  ${n}${note ? "  " + note : ""}`); if (!p) bad++; };
const { page, ctx } = await open(b, "desktop", "light", "/threads/t-idle");
const f = page.locator("#composer-field");
await f.click();
await f.pressSequentially("call plumber friday 5pm");
ok("recognised words are highlighted in the composer", (await page.locator(".composer .mirror mark").count()) >= 2);
await f.fill("");
await f.pressSequentially("ask @pr");
const pop = page.getByRole("listbox", { name: "Mention" });
await pop.waitFor();
ok("@ opens a picker grouped by kind", (await pop.getByRole("group", { name: "People" }).count()) === 1);
await page.keyboard.press("Enter");
ok("Enter inserts the mention instead of sending", (await f.inputValue()).startsWith("ask @Priya"));
await page.keyboard.press("Control+z");
ok("undo takes back the picked mention in one step", (await f.inputValue()) === "ask @pr");
await page.keyboard.press("Control+Shift+z");
ok("redo puts it back", (await f.inputValue()).startsWith("ask @Priya"));
ok("the mention becomes a removable context chip", (await page.locator(".composer .cx.on").innerText()).includes("Priya"));
await f.fill("");
await f.pressSequentially("/rev");
await page.getByRole("listbox", { name: "Skills" }).waitFor();
ok("/ at the start lists skills", true);
await page.keyboard.press("Enter");
ok("a skill is inserted as /id", (await f.inputValue()).startsWith("/review"));
await f.fill("hello agent");
const before = await page.locator(".msg").count();
await page.keyboard.press("Enter");
await page.waitForTimeout(600);
ok("Enter sends to the agent", (await page.locator(".msg").allInnerTexts()).some((t) => t.includes("hello agent")) && (await f.inputValue()) === "");
await page.keyboard.press("Control+k");
ok("Cmd-K is still the palette", (await page.getByRole("dialog", { name: "Search and commands" }).count()) === 1);
await ctx.close(); await b.close(); stop(); process.exit(bad ? 1 : 0);
