// The note editor's pickers: @, [[, # and / open the shared picker, the keys move and choose, Escape closes. Usage: node e2e/note-pickers.mjs (after `npm run build`).
import { chromium } from "playwright";
import { serve, BASE, DEVICES } from "./lib.mjs";
const stop = await serve(); const b = await chromium.launch(); let bad = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) bad++; };
const ctx = await b.newContext({ ...DEVICES.desktop }); const page = await ctx.newPage();
await page.goto(BASE + "/notes/n-2?firstrun=0");
await page.waitForSelector(".cm-content");
const text = async () => { await page.waitForTimeout(200); return page.evaluate(() => document.querySelector(".cm-content").innerText); }; // the drawn text: link brackets are partly hidden
const opts = () => page.locator('[role="listbox"] [role="option"]').allInnerTexts();
await page.locator(".cm-content").click(); await page.keyboard.press("Control+End"); await page.keyboard.press("Enter");
await page.keyboard.type("see [[Rel");
await page.waitForSelector('[role="listbox"]');
ok((await opts()).some((t) => t.includes("Release checklist")), "[[ lists notes");
await page.keyboard.press("Enter");
ok((await text()).includes("Release checklist]"), "choosing a note inserts the link");
await page.keyboard.type("#des");
await page.waitForSelector('[role="listbox"]');
ok((await opts()).some((t) => t.includes("#design")), "# lists tags");
await page.keyboard.press("Tab");
ok((await text()).includes("#design"), "Tab chooses the tag");
await page.keyboard.press("Enter");
await page.keyboard.type("@Pri");
await page.waitForSelector('[role="listbox"]');
ok((await opts()).some((t) => t.includes("Priya")), "@ lists people");
await page.keyboard.press("Escape");
// The popover fades out before it is removed: wait for the removal itself, not a fixed time.
const gone = await page.waitForSelector('[role="listbox"]', { state: "detached", timeout: 2000 }).then(() => true, () => false);
ok(gone && await page.locator('[role="listbox"]').count() === 0, "Escape closes the picker");
await page.keyboard.press("Backspace"); await page.keyboard.press("Backspace"); await page.keyboard.press("Backspace"); await page.keyboard.press("Backspace");
await page.keyboard.press("Enter");
await page.keyboard.type("/tas");
await page.waitForSelector('[role="listbox"]');
ok((await opts()).some((t) => t.includes("Task")), "/ lists the insert menu");
await page.keyboard.press("Enter");
await page.keyboard.type("write it");
ok(await page.locator(".cm-content").innerText().then((t) => t.includes("write it")), "the inserted block takes text");
const md = await page.evaluate(() => document.querySelector(".cm-content").cmView?.view?.state.doc.toString?.() ?? "");
if (md) ok(/- \[ \] write it/.test(md), "the document holds a Markdown task");
await b.close(); stop();
console.log(bad ? `${bad} FAIL` : "all pass"); process.exit(bad ? 1 : 0);
