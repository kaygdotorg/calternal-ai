import Foundation

/// Turns the web design system's token file (`packages/ui/tokens/tokens.json`, the one source) and the measured iOS Dynamic Type
/// table (`docs/native-ui-study.json`) into `Tokens.generated.swift`.
///
/// Every token in the file is either emitted or listed in `webOnly` with the reason; an unknown token fails the run, so a token added
/// on the web side cannot be silently missed here. Cost: one JSON parse and string building, microseconds; no I/O.
public enum TokenGenerator {
    /// Web-only tokens: CSS plumbing or things the platform draws itself. Each has a reason; anything not here and not handled throws.
    static let webOnly: [String: String] = [
        "type-px": "CSS rem fraction; native sizes are points",
        "icon-px": "CSS unit; native glyph sizes are points",
        "text-opsz": "variable-font optical size axis of the web font",
        "text-grad": "variable-font GRAD axis of the web font",
        "safe-top": "CSS env(); the safe area comes from the system",
        "safe-bottom": "CSS env(); the safe area comes from the system",
        "safe-left": "CSS env(); the safe area comes from the system",
        "safe-right": "CSS env(); the safe area comes from the system",
        "foot-inset": "web layout or motion token (CSS); the native client has its own",
        "r-menu": "web layout or motion token (CSS); the native client has its own",
        "ease-morph": "web layout or motion token (CSS); the native client has its own",
        "dur-morph": "web layout or motion token (CSS); the native client has its own",
        "section-above": "web layout or motion token (CSS); the native client has its own",
        "section-h": "web layout or motion token (CSS); the native client has its own",
        "section-below": "web layout or motion token (CSS); the native client has its own",
        "sheet-inset": "web sheet geometry (a CSS custom property); native sheets are the system's",
        "sheet-r-top": "web sheet geometry (a CSS custom property); native sheets are the system's",
        "sheet-r-bottom": "web sheet geometry (a CSS custom property); native sheets are the system's",
        "sheet-corners": "web sheet geometry (a CSS custom property); native sheets are the system's",
        "msg-w": "message column width; a layout rule of the web client",
        "glass-edge": "CSS inset highlight; the system's glass draws its own edge",
        "ink-rgb": "carried into line, hover, press",
        "shadow-rgb": "carried into the shadows",
        "tint": "emitted as the tint colour",
    ]

    /// Generates the Swift source. Throws a `TokenError` naming a token that is missing or not understood.
    public static func generate(tokensJSON: Data, studyJSON: Data) throws -> String {
        guard let t = try JSONSerialization.jsonObject(with: tokensJSON) as? [String: Any],
              let study = try JSONSerialization.jsonObject(with: studyJSON) as? [String: Any] else { throw TokenError("token files are not JSON objects") }
        func group(_ name: String) throws -> [String: String] {
            guard let g = t[name] as? [String: Any] else { throw TokenError("missing group \(name)") }
            return g.filter { !$0.key.hasPrefix("$") }.compactMapValues { $0 as? String }
        }
        let base = try group("base"), light = try group("light"), dark = try group("dark")
        let touch = try group("touch"), desktop = try group("desktop"), touchText = try group("touchText")
        func need(_ g: [String: String], _ k: String) throws -> String {
            guard let v = g[k] else { throw TokenError("missing token \(k)") }
            return v
        }

        var o = "// GENERATED by scripts/tokens.sh from packages/ui/tokens/tokens.json and docs/native-ui-study.json. Do not edit.\n"
        o += "// A token is added in the token file and nowhere else; `scripts/tokens.sh --check` fails when this file is stale.\n\n"
        o += "/// Calternal's design tokens, generated from the web design system's token file. Lengths are points, durations seconds, colours sRGB.\npublic enum Tokens {\n"

        // --- base ---
        var handled = Set<String>()
        func b(_ k: String) throws -> String { handled.insert(k); return try need(base, k) }
        o += "    /// Spacing scale, points.\n    public enum Space {\n"
        for i in 1...10 { o += "        public static let s\(i): Double = \(try CSS.points(b("s-\(i)")))\n" }
        o += "    }\n    /// Corner radii, points. `pill` is larger than any control, so it always draws a capsule.\n    public enum Radius {\n"
        for k in ["pill", "card", "pane", "select"] { o += "        public static let \(k): Double = \(try CSS.points(b("r-\(k)")))\n" }
        o += "    }\n    /// Durations in seconds, the two curves' control points, the one spring and the press and enter scales.\n    public enum Motion {\n"
        for k in ["fast", "base", "slow", "leave", "pulse"] { o += "        public static let \(k): Double = \(try CSS.seconds(b("dur-\(k)")))\n" }
        o += "        public static let pressScale: Double = \(try CSS.number(b("press-scale")))\n"
        o += "        public static let enterScale: Double = \(try CSS.number(b("enter-scale")))\n"
        o += "        public static let easeOut = Bezier(\(bez(try CSS.bezier(b("ease-out")))))\n"
        guard let sp = (t["springs"] as? [String: Any])?["spring"] as? [Double], sp.count == 2 else { throw TokenError("missing springs.spring") }
        o += "        /// Damping ratio and response in seconds of the one spring.\n        public static let springDamping: Double = \(sp[0])\n        public static let springResponse: Double = \(sp[1])\n    }\n"
        o += "    /// Sizes that are the same on every form.\n    public enum Layout {\n"
        for (swift, k) in [("inset", "inset"), ("tierCap", "tier-cap"), ("capOffset", "cap-offset"), ("sidebarWidth", "side-w"), ("rightWidth", "right-w")] {
            o += "        public static let \(swift): Double = \(try CSS.points(b(k)))\n"
        }
        o += "    }\n    /// Font weights, in the web scale (100...900); the native weight is the nearest.\n    public enum Weight {\n"
        for (swift, k) in [("ui", "ui-weight"), ("body", "body-weight"), ("strong", "strong-weight")] { o += "        public static let \(swift): Int = \(try CSS.number(b(k)).rounded().asInt)\n" }
        o += "    }\n    /// The design's font families; the native default is the system font, these are what a font setting can name.\n    public enum Family {\n"
        for (swift, k) in [("ui", "font-ui"), ("rounded", "font-rounded"), ("mono", "font-mono"), ("terminal", "font-terminal")] {
            let name = try b(k).split(separator: ",")[0].trimmingCharacters(in: CharacterSet(charactersIn: "\" "))
            o += "        public static let \(swift) = \"\(name)\"\n"
        }
        o += "    }\n"
        let sat = try b("glass-sat"); guard sat.hasSuffix("%") else { throw TokenError("glass-sat is not a percentage") }
        o += "    /// Saturation multiplier behind glass surfaces (1.8 is 180 %).\n    public static let glassSaturation: Double = \(try CSS.number(String(sat.dropLast())) / 100)\n"
        guard let grain = (t["appearance"] as? [String: Any])?["grain-a"] as? String else { throw TokenError("missing appearance.grain-a") }
        o += "    /// Strength of the optional grain over wallpapers, 0 turns it off.\n    public static let grain: Double = \(try CSS.number(grain))\n"
        let accentBase = try CSS.hex(b("accent-base"))
        o += "    /// The default accent before one is inferred from the wallpaper.\n    public static let accentBase = \(rgba(accentBase))\n"
        // The mockup's 3 by 3 colour mesh stands behind a surface until a wallpaper is ready.
        guard let backdrop = t["backdrop"] as? [String: Any] else { throw TokenError("missing backdrop") }
        for k in base.keys where !handled.contains(k) && webOnly[k] == nil { throw TokenError("base token \(k) is not handled by the Swift generator; emit it or list it in webOnly") }

        // --- form tokens ---
        func form(_ name: String, _ g: [String: String], text: String) throws -> String {
            var h = Set<String>()
            func f(_ k: String) throws -> String { h.insert(k); return try need(g, k) }
            var s = "    public static let \(name) = FormTokens(\n"
            s += "        rowHeight: \(try CSS.points(f("row-h"))), settingsRowHeight: \(try CSS.points(f("row-h-settings"))),\n"
            s += "        barHeight: \(try CSS.points(f("bar-h"))), pillHeight: \(try CSS.points(f("pill-h"))), smallControl: \(try CSS.points(f("ib-small"))),\n"
            s += "        padRegion: \(try CSS.points(f("pad-region"))), blurScale: \(try CSS.number(f("blur-scale"))),\n"
            s += "        glyph: \(try CSS.points(f("glyph"))), glyphStroke: \(try CSS.number(f("glyph-stroke"))), glyphInline: \(try CSS.points(f("glyph-inline"))), glyphInlineStroke: \(try CSS.number(f("glyph-inline-stroke"))),\n"
            s += "        sheetDuration: \(try CSS.seconds(f("dur-sheet"))), sheetCurve: Bezier(\(bez(try CSS.bezier(f("ease-sheet"))))),\n"
            s += text
            s += "    )\n"
            for k in g.keys where !h.contains(k) && webOnly[k] == nil && !k.hasPrefix("text-") { throw TokenError("\(name) token \(k) is not handled by the Swift generator") }
            return s
        }
        let roles = ["title", "heading", "ui", "code", "label", "section"]
        var deskText = "        text: TextScale(\n"
        for r in roles { deskText += "            \(r): TextToken(size: \(try CSS.points(need(desktop, "text-\(r)"))), style: nil)\(r == "section" ? "" : ",")\n" }
        deskText += "        )\n"
        guard let ios = study["ios"] as? [String: Any], let dt = ios["dynamicType"] as? [String: Any], let sizes = dt["sizes"] as? [String],
              let large = sizes.firstIndex(of: "large") else { throw TokenError("native-ui-study.json has no ios.dynamicType") }
        var touchTextS = "        text: TextScale(\n"
        for r in roles {
            let style = try need(touchText, "text-\(r)")
            guard let rows = dt[style] as? [[Double]], rows.count > large else { throw TokenError("native-ui-study.json has no Dynamic Type style \(style)") }
            let swiftStyle = style == "headlineBody" ? "body" : style
            touchTextS += "            \(r): TextToken(size: \(rows[large][0]), style: .\(swiftStyle))\(r == "section" ? "" : ",")\n"
        }
        touchTextS += "        )\n"
        o += "    /// Desktop (fine pointer and hover): compact rows, 18 pt glyphs, full blur. Text sizes are fixed points.\n"
        o += try form("desktop", desktop, text: deskText)
        o += "    /// Phones and tablets: larger hit targets, lighter blur. Text sizes are the measured Dynamic Type \"Large\" sizes and `style` is the text style that scales them.\n"
        o += try form("touch", touch, text: touchTextS)

        // --- schemes ---
        o += "    /// The colours of the light scheme.\n    public static let light = \(try scheme(light, backdrop: backdrop["light"], mixWith: Colour(r: 0, g: 0, b: 0, a: 1), mixPercent: 80, softPercent: 14))\n"
        o += "    /// The colours of the dark scheme.\n    public static let dark = \(try scheme(dark, backdrop: backdrop["dark"], mixWith: Colour(r: 1, g: 1, b: 1, a: 1), mixPercent: 72, softPercent: 22))\n"
        o += "}\n"
        return o
    }

    private static func bez(_ v: [Double]) -> String { "\(v[0]), \(v[1]), \(v[2]), \(v[3])" }
    private static func rgba(_ c: Colour) -> String { "RGBA(\(c.r.r4), \(c.g.r4), \(c.b.r4), \(c.a.r4))" }

    /// One `SchemeColors` literal. The accent is `color-mix(in oklab, base P%, black|white)` on the web: the percentage and the colour mixed with are emitted, and `Theme` mixes at run time so the base can come from the wallpaper.
    private static func scheme(_ g: [String: String], backdrop: Any?, mixWith: Colour, mixPercent: Double, softPercent: Double) throws -> String {
        func need(_ k: String) throws -> String { guard let v = g[k] else { throw TokenError("missing scheme token \(k)") }; return v }
        let vars: [String: Colour] = ["ink-rgb": try CSS.triple(need("ink-rgb")), "shadow-rgb": try CSS.triple(need("shadow-rgb")), "tint": try CSS.triple(need("tint"))]
        let known: Set<String> = ["tint", "paper", "ink", "ink-2", "ink-3", "ink-4", "line", "hover", "press", "accent", "accent-soft", "danger", "good", "warn", "info", "scrim",
                                  "glass-a", "glass-blur", "glass-bright", "shadow-card", "shadow-float", "ink-rgb", "shadow-rgb"]
        for k in g.keys where !known.contains(k) && webOnly[k] == nil { throw TokenError("scheme token \(k) is not handled by the Swift generator") }
        let accentExpr = try need("accent"), softExpr = try need("accent-soft")
        guard accentExpr.contains("color-mix(in oklab, var(--accent-base) \(Int(mixPercent))%"), accentExpr.hasSuffix(mixWith.r == 0 ? ", black)" : ", white)"), softExpr.contains("var(--accent-base) \(Int(softPercent))%, transparent") else {
            throw TokenError("accent expressions changed shape: \(accentExpr) / \(softExpr); update the generator")
        }
        guard let mesh = backdrop as? [String], mesh.count == 9 else { throw TokenError("backdrop mesh needs nine colours") }
        func shadows(_ s: String) throws -> String {
            let layers = try CSS.topLevelCommas(s).map { layer -> String in
                let p = layer.components(separatedBy: " rgb(")
                guard p.count == 2 else { throw TokenError("unparsed shadow layer: \(layer)") }
                let n = try p[0].split(separator: " ").map { try CSS.points(String($0)) }
                guard n.count == 4 else { throw TokenError("shadow layer needs x y blur spread: \(layer)") }
                let c = try CSS.rgba("rgb(" + p[1], vars: vars)
                return "Shadow(x: \(n[0]), y: \(n[1]), blur: \(n[2]), spread: \(n[3]), color: \(rgba(c)))"
            }
            return "[" + layers.joined(separator: ", ") + "]"
        }
        func solid(_ k: String) throws -> String { rgba(try CSS.hex(need(k))) }
        func over(_ k: String) throws -> String { rgba(try CSS.rgba(need(k), vars: vars)) }
        return """
        SchemeColors(
                tint: \(rgba(vars["tint"]!)), paper: \(try solid("paper")),
                ink: \(try solid("ink")), ink2: \(try solid("ink-2")), ink3: \(try solid("ink-3")), ink4: \(try solid("ink-4")),
                line: \(try over("line")), hover: \(try over("hover")), press: \(try over("press")),
                accentMixPercent: \(mixPercent), accentMixTowards: \(rgba(mixWith)), accentSoftAlpha: \(softPercent / 100),
                danger: \(try solid("danger")), good: \(try solid("good")), warn: \(try solid("warn")), info: \(try solid("info")),
                scrim: \(try over("scrim")),
                glassAlpha: \(try CSS.number(need("glass-a"))), glassBlur: \(try CSS.points(need("glass-blur"))), glassBrightness: \(try CSS.number(need("glass-bright"))),
                shadowCard: \(try shadows(need("shadow-card"))),
                shadowFloat: \(try shadows(need("shadow-float"))),
                backdrop: [\(try mesh.map { rgba(try CSS.hex($0)) }.joined(separator: ", "))]
            )
        """
    }
}

private extension Double {
    /// Four decimals, trimmed: the generated file stays readable and stable.
    var r4: String { let v = (self * 10000).rounded() / 10000; return "\(v)" }
    var asInt: String { "\(Int(self))" }
}
