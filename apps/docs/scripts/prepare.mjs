// Prepares what the theme needs from the design system, before the site builds: the two fonts (copied from the web app's font step), the colour tokens as
// CSS, and the preset palettes as JSON. Everything it writes is generated, gitignored and derived from `packages/ui/tokens/tokens.json` and the web app's
// `presets.ts`, so the documentation and the app cannot drift apart. Cost: a few file copies and one JSON read; no network.
import { spawnSync } from "node:child_process";
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const site = join(here, "..");
const root = join(site, "../..");
const tokens = JSON.parse(readFileSync(join(root, "packages/ui/tokens/tokens.json"), "utf8"));

// 1. Fonts: the web app's step copies them (Google Sans Flex, its dark-ink family, Maple Mono) into apps/web/public/fonts.
const r = spawnSync("node", ["scripts/fonts.mjs"], { cwd: join(root, "apps/web"), stdio: "inherit" });
if (r.status !== 0) throw new Error("the web app's font step failed");
const out = join(site, "public/fonts");
mkdirSync(out, { recursive: true });
for (const f of ["google-sans-flex-latin-opsz-normal.woff2", "google-sans-flex-latin-ext-opsz-normal.woff2", "google-sans-flex-latin-opsz-grad-normal.woff2", "google-sans-flex-latin-ext-opsz-grad-normal.woff2", "maple-mono-latin-400-normal.woff2", "maple-mono-latin-500-normal.woff2"]) {
  copyFileSync(join(root, "apps/web/public/fonts", f), join(out, f));
}

// 2. Colour tokens: three variables per scheme (paper, ink, accent); every Starlight colour is mixed from them in calternal.css, so a preset changes only these.
const t = tokens;
// The default look's wallpaper, as the two tiny pre-blurred renditions the app paints on its first paint (apps/web/scripts/wallpapers.mjs); the page shows it behind a veil.
// Absent in a build without them: the site is then flat, as before.
const wallId = t.appearance["default-wallpaper"];
const wall = {};
for (const [k, f] of [["light", `${wallId}-blur-light.jpg`], ["dark", `${wallId}-blur.jpg`]]) {
  try { mkdirSync(join(site, "public/wallpapers"), { recursive: true }); copyFileSync(join(root, "apps/web/public/wallpapers", f), join(site, "public/wallpapers", f)); wall[k] = f; } catch { /* not fetched */ }
}
const base = (process.env.DOCS_BASE || "/docs/");
const wallVar = (k) => (wall[k] ? `url("${base}wallpapers/${wall[k]}")` : "none");
const css = `/* GENERATED by apps/docs/scripts/prepare.mjs from packages/ui/tokens/tokens.json. Do not edit. */
:root { --cal-paper: ${t.light.paper}; --cal-ink: ${t.light.ink}; --cal-accent: ${t.base["accent-base"]}; --cal-opsz: ${t.base["text-opsz"]}; --cal-grad: ${t.light["text-grad"]}; --cal-weight: ${t.base["ui-weight"]}; --cal-wall: ${wallVar("light")}; --cal-r-card: ${t.base["r-card"] ?? "14px"}; --cal-r-select: ${t.base["r-select"] ?? "8px"}; --cal-r-pill: 999px; --cal-pill-h: ${t.desktop["pill-h"] ?? "38px"}; --cal-dur-fast: ${t.base["dur-fast"]}; --cal-dur-base: ${t.base["dur-base"]}; --cal-ease: ${t.base["ease-out"]}; --cal-press: ${t.base["press-scale"] ?? "0.97"}; }
:root[data-theme='dark'] { --cal-paper: ${t.dark.paper}; --cal-ink: ${t.dark.ink}; --cal-accent: ${t.base["accent-base"]}; --cal-grad: ${t.dark["text-grad"]}; --cal-wall: ${wallVar("dark")}; }
`;
mkdirSync(join(site, "src/styles"), { recursive: true });
writeFileSync(join(site, "src/styles/tokens.generated.css"), css);

// 3. Presets: the web app's themed presets (paper, ink, accent per scheme) for the picker.
const { PRESETS } = await import(join(root, "apps/web/src/appearance/presets.ts"));
const presets = [{ id: "calternal", name: "Calternal", light: null, dark: null }, ...PRESETS.filter((p) => p.theme).map((p) => ({ id: p.id, name: p.name, light: { paper: p.theme.light.paper, ink: p.theme.light.ink, accent: p.theme.light.accent }, dark: { paper: p.theme.dark.paper, ink: p.theme.dark.ink, accent: p.theme.dark.accent } }))];
writeFileSync(join(site, "src/presets.generated.json"), JSON.stringify(presets));
console.log(`docs theme: tokens, ${presets.length} presets, 6 font files`);
